"""Reports: Markdown (PR comment / step summary), JSON (evidence for the Release Gate), JUnit XML."""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr

from k11_api_qa.runner import FlowResult

from . import __version__

ICON = {"passed": "✅", "failed": "❌", "blocked": "⛔", "error": "⚠️", "skipped": "⏭️"}
REPORT_DIR = ".qa-mcp/integration-report"


def counts(results: list[FlowResult]) -> dict:
    c = {"flows": len(results), "passed": 0, "failed": 0, "blocked": 0, "error": 0}
    for r in results:
        c[r.status] = c.get(r.status, 0) + 1
    steps = [s for r in results for s in r.steps if not s.cleanup]
    kinds = [s.kind for s in steps]
    c["steps"] = len(steps)
    c["messages_published"] = kinds.count("publish")
    c["messages_expected"] = sum(k in ("expect_message", "expect_no_message") for k in kinds)
    c["message_expectations_failed"] = sum(s.kind in ("expect_message", "expect_no_message") and s.status != "passed" for s in steps)
    c["schema_violations"] = sum(1 for s in steps for a in s.assertions if a["check"].startswith("matches AsyncAPI") and not a["ok"])
    c["jobs_run"] = kinds.count("run_job")
    c["jobs_failed"] = sum(s.kind == "run_job" and s.status != "passed" for s in steps)
    c["waits_timed_out"] = sum(s.kind == "wait_until" and s.status == "failed" for s in steps)
    c["server_errors"] = sum(1 for s in steps if s.response and isinstance(s.response.get("status"), int) and s.response["status"] >= 500)
    return c


def to_dict(results: list[FlowResult], environment: str) -> dict:
    c = counts(results)
    status = "not_run" if not results else "completed"
    reason = ("no integration flows found (tests/integration/*.yaml)" if not results else
              "all flows passed" if c["passed"] == c["flows"] else
              f"{c['flows'] - c['passed']} of {c['flows']} flow(s) did not pass")
    return {"tool": f"k11-integration-qa-mcp {__version__}",
            "generatedAt": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            "environment": environment, "status": status, "reason": reason, "summary": c,
            "flows": [asdict(r) for r in results]}


def _step_line(s) -> list[str]:
    L = [f"- **{s.name}** (`{s.kind}`){' (cleanup)' if s.cleanup else ''}: {s.status}"]
    if s.error:
        L.append(f"  - {s.error}")
    req = s.request or {}
    if "method" in req:
        L.append(f"  - request: `{req['method']} {req['url']}`")
    elif "publish" in req:
        L.append(f"  - published to `{req['publish']}`")
    elif "topic" in req:
        L.append(f"  - topic `{req['topic']}`, waited {req.get('within_s', 0):g}s")
    elif "job" in req:
        L.append(f"  - job `{req['job']}`")
    if s.query:
        L.append(f"  - query on `{s.query['database']}`: `{' '.join(s.query['sql'].split())[:160]}`")
    for a in s.assertions:
        if not a["ok"]:
            L.append(f"  - ✗ {a['check']}" + (f": {a['detail']}" if a.get("detail") else ""))
    out = (s.response or {}).get("output")
    if out and s.status != "passed":
        L.append("  - job output: `" + " ⏎ ".join(out.splitlines()[-3:])[:300] + "`")
    return L


def to_markdown(results: list[FlowResult], environment: str) -> str:
    c = counts(results)
    if not results:
        head = "⚠️ No integration flows ran"
    else:
        head = "✅ All flows passed" if c["passed"] == c["flows"] else "❌ Some flows did not pass"
    L = [f"## Integration tests: {head}", "",
         f"Environment **{environment}**: {c['flows']} flow(s), **{c['passed']} passed**, {c['failed']} failed, "
         f"{c['blocked']} blocked, {c['error']} errors; {c['steps']} steps, {c['messages_published']} message(s) published, "
         f"{c['messages_expected']} message expectation(s), {c['jobs_run']} job run(s)"
         + (f"; **{c['schema_violations']} AsyncAPI schema violation(s)**" if c["schema_violations"] else "") + ".", ""]
    if results:
        L += ["| Flow | Result | Steps | Time |", "|---|---|---|---|"]
        for r in results:
            main = [s for s in r.steps if not s.cleanup]
            L.append(f"| {r.name} | {ICON.get(r.status, '')} {r.status} | {sum(s.status == 'passed' for s in main)}/{len(main)} | {r.ms} ms |")
        L.append("")
    for r in results:
        if r.status == "passed":
            continue
        L += [f"### {ICON.get(r.status, '')} {r.name}", f"`{r.file}`" if r.file else "", ""]
        if r.error:
            L += [f"> {r.error}", ""]
        for s in r.steps:
            if s.status not in ("passed", "skipped"):
                L += _step_line(s)
        L.append("")
    L.append(f"<sub>Generated by k11-integration-qa-mcp {__version__}. Full evidence (messages, queries, job output): "
             "integration-report.json.</sub>")
    return "\n".join(L) + "\n"


def to_junit(results: list[FlowResult]) -> str:
    c = counts(results)
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           f'<testsuites name="integration" tests="{c["flows"]}" failures="{c["failed"] + c["blocked"]}" errors="{c["error"]}">']
    for r in results:
        main = [s for s in r.steps if not s.cleanup]
        fails = sum(s.status in ("failed", "blocked") for s in main)
        errs = sum(s.status == "error" for s in main) + (1 if r.error else 0)
        out.append(f'  <testsuite name={quoteattr(r.name)} tests="{len(main) or 1}" failures="{fails}" errors="{errs}" time="{r.ms / 1000:.3f}">')
        if r.error and not main:
            out.append(f'    <testcase name="load" classname={quoteattr(r.file or r.name)}><error message={quoteattr(r.error)}/></testcase>')
        for s in main:
            out.append(f'    <testcase name={quoteattr(s.name)} classname={quoteattr(r.file or r.name)} time="{(s.ms or 0) / 1000:.3f}">')
            if s.status == "failed":
                msg = "; ".join(f"{a['check']}: {a.get('detail', '')}" for a in s.assertions if not a["ok"]) or (s.error or "failed")
                out.append(f"      <failure message={quoteattr(msg[:500])}>{escape(json.dumps(s.response or {}, default=str)[:2000])}</failure>")
            elif s.status in ("blocked", "error"):
                tag = "failure" if s.status == "blocked" else "error"
                out.append(f"      <{tag} message={quoteattr((s.error or s.status)[:500])}/>")
            elif s.status == "skipped":
                out.append("      <skipped/>")
            out.append("    </testcase>")
        out.append("  </testsuite>")
    out.append("</testsuites>")
    return "\n".join(out) + "\n"


def write(results: list[FlowResult], environment: str, out_dir: Path) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {"markdown": out_dir / "integration-report.md", "json": out_dir / "integration-report.json",
             "junit": out_dir / "integration-junit.xml"}
    paths["markdown"].write_text(to_markdown(results, environment), "utf8")
    paths["json"].write_text(json.dumps(to_dict(results, environment), indent=2, ensure_ascii=False, default=str) + "\n", "utf8")
    paths["junit"].write_text(to_junit(results), "utf8")
    return paths
